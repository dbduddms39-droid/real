#!/usr/bin/env python3
"""Build an offline icon bundle from the original PNGs and source manifest."""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build():
    manifest = json.loads((ROOT / 'assets/icons/sources.json').read_text())
    icons = {}
    for record in manifest['icons']:
        data = (ROOT / 'assets/icons' / record['file']).read_bytes()
        if hashlib.sha256(data).hexdigest() != record['sha256']:
            raise ValueError(f"Icon integrity mismatch: {record['file']}")
        icons[record['name']] = {
            'data': 'data:image/png;base64,' + base64.b64encode(data).decode(),
            'width': record['width'], 'height': record['height'],
            'viewBox': record['view_box'],
        }
    script = '// Generated by build-icons.py from original Apple artwork; see assets/icons/sources.json.\n'
    script += 'window.PhoneIconAssets = ' + json.dumps(icons, ensure_ascii=False, separators=(',', ':')) + ';\n'
    (ROOT / 'icon-assets.js').write_text(script)
    print(f'Bundled {len(icons)} original icons for offline use.')


if __name__ == '__main__':
    build()
